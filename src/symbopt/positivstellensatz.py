@dataclass(frozen=True)
class PreorderingGenerator:
    """Square-free product of nonnegative inequality generators."""

    indices: tuple[int, ...]
    polynomial: sp.Expr


@dataclass(frozen=True)
class PositivstellensatzCertificate:
    """Exact real infeasibility certificate for equalities and ``g_i >= 0``.

    The certificate proves ``-1`` belongs to the preordering generated by the
    inequalities modulo the ideal generated by the equalities.
    """

    sos_certificate: SOSCertificate
    generators: tuple[PreorderingGenerator, ...]
    equalities: tuple[sp.Expr, ...]
    groebner_basis: tuple[sp.Expr, ...]
    gram_bases: tuple[tuple[sp.Expr, ...], ...]
    gram_multipliers: tuple[sp.Expr | None, ...]
    ideal_remainder: sp.Expr
    exact_psd_checks: tuple[bool | None, ...]
    verified: bool
    inequalities: tuple[sp.Expr, ...]


@dataclass(frozen=True)
class PositivstellensatzResult:
    """Infeasibility search outcome with its optional independently checked polynomial certificate."""

    attempted: bool
    certified: bool
    status: str
    certificate: PositivstellensatzCertificate | None
    plan: SOSSearchPlan
    message: str
    diagnostics: Mapping[str, object] = field(default_factory=dict)


def preordering_generators(
    inequalities: Sequence[sp.Expr],
    *,
    max_product_order: int | None = None,
) -> tuple[PreorderingGenerator, ...]:
    """Return nonempty square-free products of inequality generators."""
    normalized = []
    for expr in inequalities:
        expr = sp.sympify(expr)
        if isinstance(expr, (sp.GreaterThan, sp.StrictGreaterThan)):
            expr = expr.lhs - expr.rhs
        elif isinstance(expr, (sp.LessThan, sp.StrictLessThan)):
            expr = expr.rhs - expr.lhs
        elif isinstance(expr, sp.Equality):
            raise TypeError(
                "preordering generators must be inequalities, not equalities"
            )
        normalized.append(sp.expand(expr))
    inequalities = tuple(normalized)
    count = len(inequalities)
    if max_product_order is None:
        max_product_order = count
    if not isinstance(max_product_order, int) or max_product_order < 0:
        raise ValueError("max_product_order must be a nonnegative integer or None.")
    max_product_order = min(max_product_order, count)
    result = []
    for order in range(1, max_product_order + 1):
        for subset in combinations(range(count), order):
            product = sp.expand(sp.prod(inequalities[index] for index in subset))
            result.append(PreorderingGenerator(subset, product))
    return tuple(result)


def _groebner_data(equalities, variables):
    if not equalities:
        return (), None
    try:
        basis = sp.groebner(equalities, *variables, order="grevlex", domain=sp.QQ)
    except (PolynomialError, TypeError, ValueError, NotImplementedError) as exc:
        raise ValueError(
            "Equality constraints must define a polynomial ideal."
        ) from exc
    return tuple(sp.expand(poly.as_expr()) for poly in basis.polys), basis


def _reduce_mod_ideal(expr, equalities, variables, groebner=None):
    if not equalities:
        return sp.expand(expr)
    if groebner is None:
        _, groebner = _groebner_data(equalities, variables)
    try:
        _, remainder = groebner.reduce(expr)
        return sp.expand(remainder)
    except CoercionFailed:
        # Exact algebraic Gram recovery can introduce radical/RootOf
        # coefficients even when the equality ideal itself is rational. EX
        # preserves exact coefficients without converting them to floats.
        algebraic_basis = sp.groebner(
            equalities, *variables, order="grevlex", domain=sp.EX
        )
        _, remainder = algebraic_basis.reduce(expr)
        return sp.expand(remainder)


def _gram_expression(certificate, compilation):
    expression = sp.Integer(0)
    for block, matrix in zip(compilation.gram_blocks, certificate.gram_matrices):
        basis = sp.Matrix(block.basis)
        term = sp.expand((basis.T * matrix * basis)[0])
        if block.multiplier is not None:
            term = sp.expand(block.multiplier * term)
        expression += term
    return sp.expand(expression)


def verify_infeasibility_certificate(
    certificate: PositivstellensatzCertificate,
    variables: sp.Symbol | Sequence[sp.Symbol] | None = None,
    *,
    equalities=None,
    inequalities=None,
) -> bool:
    """Replay the identity and bind its preordering to the source inequalities.

    Supplied source premises must match the stored premises. Generator indices
    identify nonempty square-free products of those inequalities. Stored
    Gröbner and PSD summaries are not substitutes for recomputation.
    """
    if type(certificate) is not PositivstellensatzCertificate:
        return False
    try:
        if (
            equalities is not None
            and tuple(map(sp.sympify, equalities)) != certificate.equalities
        ):
            return False
        if (
            inequalities is not None
            and tuple(map(sp.sympify, inequalities)) != certificate.inequalities
        ):
            return False
        products = []
        for generator in certificate.generators:
            indices = generator.indices
            if (
                type(generator) is not PreorderingGenerator
                or not indices
                or tuple(sorted(set(indices))) != indices
                or any(
                    type(i) is not int or not 0 <= i < len(certificate.inequalities)
                    for i in indices
                )
            ):
                return False
            expected = sp.expand(sp.prod(certificate.inequalities[i] for i in indices))
            if generator.polynomial != expected:
                return False
            products.append(expected)
        proof = certificate.sos_certificate
        if type(proof) is not SOSCertificate or not proof.verify(
            polynomial=-1,
            lower_bound=0,
            inequalities=products,
            equalities=certificate.equalities,
        ):
            return False
        if (
            tuple(proof.gram_bases) != certificate.gram_bases
            or tuple(sp.S.One if g is None else g for g in certificate.gram_multipliers)
            != proof.gram_multipliers
            or tuple(proof.exact_psd_checks) != certificate.exact_psd_checks
            or certificate.verified is not True
            or certificate.ideal_remainder != 0
        ):
            return False
    except (AttributeError, TypeError, ValueError, ArithmeticError):
        return False
    normalized = normalize_variables(variables)
    if normalized is None:
        normalized = proof.variables
    variables = tuple(normalized)
    if len(certificate.gram_bases) != len(certificate.sos_certificate.gram_matrices):
        return False
    if len(certificate.gram_multipliers) != len(certificate.gram_bases):
        return False
    gram_expression = sp.Integer(0)
    for basis_terms, matrix, multiplier in zip(
        certificate.gram_bases,
        certificate.sos_certificate.gram_matrices,
        certificate.gram_multipliers,
    ):
        basis = sp.Matrix(basis_terms)
        term = sp.expand((basis.T * matrix * basis)[0])
        gram_expression += term if multiplier is None else sp.expand(multiplier * term)
    residual = sp.expand(sp.Integer(-1) - proof.normalization_scale * gram_expression)
    try:
        basis, groebner = _groebner_data(certificate.equalities, variables)
        if basis != certificate.groebner_basis or tuple(variables) != proof.variables:
            return False
        if groebner is not None:
            residual = _reduce_mod_ideal(
                residual, certificate.equalities, variables, groebner
            )
    except (ValueError, PolynomialError, TypeError, NotImplementedError):
        return False
    residual = sp.cancel(sp.together(sp.expand(residual)))
    return residual == 0 or residual.is_zero is True


def search_infeasibility_certificate(
    equalities: Sequence[sp.Expr] = (),
    inequalities: Sequence[sp.Expr] = (),
    variables: sp.Symbol | Sequence[sp.Symbol] | None = None,
    *,
    constraints: object = None,
    max_product_order: int | None = None,
    multiplier_degree: int = 1,
    equality_degree: int | None = None,
    planner: bool = True,
    force: bool = False,
    solver_config: SDPSolverConfig | None = None,
) -> PositivstellensatzResult:
    """Search for an exact Positivstellensatz-style real infeasibility proof.

    Inequalities use the convention ``g_i >= 0``. The search forms square-free
    products of the generators, assigns each product an SOS multiplier, and
    asks the SDP layer for an exact recovery of ``-1`` modulo equality
    multipliers. The final proof is independently reduced modulo an exact
    Gröbner basis of the equality ideal.
    """
    _, normalized_variables, inequalities, equalities = _normalize_sos_domain(
        sp.Integer(0), variables, inequalities, equalities, constraints
    )
    variables = tuple(normalized_variables)
    if not variables:
        raise ValueError("could not infer any variables for the infeasibility problem")
    extras = set().union(
        *(expr.free_symbols for expr in (*equalities, *inequalities))
    ) - set(variables)
    if extras:
        raise ValueError("Constraints contain symbols outside variables.")

    products = preordering_generators(inequalities, max_product_order=max_product_order)
    product_polys = tuple(item.polynomial for item in products)
    basis_exprs, groebner = _groebner_data(equalities, variables)

    if equality_degree is None:
        max_product_degree = 0
        for product in product_polys:
            max_product_degree = max(
                max_product_degree,
                int(sp.Poly(product, *variables).total_degree()),
            )
        min_eq_degree = min(
            (int(sp.Poly(eq, *variables).total_degree()) for eq in equalities),
            default=0,
        )
        equality_degree = max(1, max_product_degree - min_eq_degree)

    plan = plan_sos_search(
        sp.Integer(-1),
        variables,
        inequalities=product_polys,
        equalities=equalities,
        ineq_mult_degree=multiplier_degree,
        eq_mult_degree=equality_degree,
    )
    if planner and not force and not plan.launch:
        return PositivstellensatzResult(
            False,
            False,
            "deferred",
            None,
            plan,
            plan.reason,
            {"preordering_generator_count": len(products)},
        )

    search = search_sos_certificate(
        sp.Integer(-1),
        variables,
        inequalities=product_polys,
        equalities=equalities,
        ineq_mult_degree=multiplier_degree,
        eq_mult_degree=equality_degree,
        planner=False,
        force=True,
        solver_config=solver_config,
    )
    if not search.certified or search.certificate is None or search.raw_result is None:
        return PositivstellensatzResult(
            True,
            False,
            "uncertified",
            None,
            plan,
            search.message,
            {"preordering_generator_count": len(products), "sos_status": search.status},
        )

    compilation = search.raw_result.compilation
    if compilation is None:
        return PositivstellensatzResult(
            True,
            False,
            "failed",
            None,
            plan,
            "SOS result omitted compilation metadata.",
            {"preordering_generator_count": len(products)},
        )
    gram_expression = _gram_expression(search.certificate, compilation)
    identity_residual = sp.expand(sp.Integer(-1) - gram_expression)
    if groebner is None:
        remainder = identity_residual
    else:
        try:
            remainder = _reduce_mod_ideal(
                identity_residual, equalities, variables, groebner
            )
        except (PolynomialError, TypeError, ValueError, NotImplementedError) as exc:
            return PositivstellensatzResult(
                True,
                False,
                "failed",
                None,
                plan,
                f"Exact Gröbner reduction failed: {exc}",
                {"preordering_generator_count": len(products)},
            )

    exact_psd = tuple(search.certificate.exact_psd_checks)
    zero_remainder = remainder == 0 or remainder.is_zero is True
    verified = bool(zero_remainder and all(check is True for check in exact_psd))
    gram_bases = tuple(tuple(block.basis) for block in compilation.gram_blocks)
    gram_multipliers = tuple(block.multiplier for block in compilation.gram_blocks)
    certificate = PositivstellensatzCertificate(
        search.certificate,
        products,
        equalities,
        basis_exprs,
        gram_bases,
        gram_multipliers,
        remainder,
        exact_psd,
        verified,
        inequalities,
    )
    verified = verified and verify_infeasibility_certificate(certificate, variables)
    return PositivstellensatzResult(
        True,
        verified,
        "certified" if verified else "verification_failed",
        certificate if verified else None,
        plan,
        "Recovered exact preordering certificate modulo the equality ideal."
        if verified
        else "Recovered SOS data failed exact Positivstellensatz verification.",
        {
            "preordering_generator_count": len(products),
            "max_product_order": max_product_order,
            "equality_degree": equality_degree,
        },
    )
