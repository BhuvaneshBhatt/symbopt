def test_reference_inventory_json_matches_python_map():
    import json
    from pathlib import Path

    data = json.loads(
        Path(__file__)
        .parent.joinpath("by_input_type", "reference_case_inventory.json")
        .read_text()
    )
    assert [item["case"] for item in data] == list(range(1, 292))
    assert {item["case"]: item["family"] for item in data} == CASE_FAMILY
